"""Model card + datasheet export (Markdown), following Mitchell et al. (2019) "Model Cards for
Model Reporting" and Gebru et al. (2021) "Datasheets for Datasets"."""
from datetime import date
from typing import Any, Dict, Optional

import pandas as pd

from src.config import DATASET_CONFIGS, get_outcome_labels


def _f(v: Any, nd: int = 4) -> str:
    try:
        return f"{float(v):.{nd}f}"
    except (TypeError, ValueError):
        return "n/a"


def _metric_row(name: str, info: Dict[str, Any]) -> str:
    signed = ""
    if "signed_ci_low" in info:
        signed = f"[{_f(info['signed_ci_low'])}, {_f(info['signed_ci_high'])}]"
    sig = info.get("is_significant")
    sig_txt = "n/a" if sig is None else ("**Yes**" if bool(sig) else "No")
    return f"| {name} | {_f(info.get('val'))} | [{_f(info.get('ci_low'))}, {_f(info.get('ci_high'))}] | {signed or 'n/a'} | {sig_txt} |"


def generate_model_card(
    dataset_key: str,
    dataset_name: str,
    model_label: str,
    protected_col: str,
    kpis: Dict[str, Any],
    baseline_pred_metrics: Dict[str, Any],
    baseline_fairness: Dict[str, Any],
    mitigations: Dict[str, Any],
    split_sizes: Dict[str, int],
    feature_count: int,
    selected_eps: Optional[float] = None,
    dedup_info: Optional[Dict[str, Any]] = None,
    metrics_source: str = "live run (seed 42)",
    intersectional: Optional[Dict[str, Any]] = None,
    calibration: Optional[Dict[str, Any]] = None,
) -> str:
    cfg = DATASET_CONFIGS.get(dataset_key, {})
    labels = get_outcome_labels(dataset_key)
    prot_cfg = cfg.get("protected_attributes", {}).get(protected_col, {})
    source = cfg.get("url") or (f"UCI Machine Learning Repository, dataset id {cfg['uci_id']}" if cfg.get("uci_id") else "User-uploaded CSV")
    L = []
    add = L.append

    add(f"# Model Card — {model_label} on {dataset_name}")
    add(f"_Generated by FairLens on {date.today().isoformat()}. Metrics source: {metrics_source}._\n")

    add("## 1. Model Details")
    add(f"- **Model:** {model_label} (scikit-learn / XGBoost), binary classifier.")
    add(f"- **Prediction target:** `{cfg.get('target_column', 'target')}` — favorable outcome = **{labels['favorable']}** (label {labels['favorable_value']}); unfavorable = **{labels['unfavorable']}** (label {labels['unfavorable_value']}).")
    add(f"- **Protected attribute audited:** `{protected_col}`" + (f" (privileged: `{prot_cfg.get('privileged')}`, unprivileged: `{prot_cfg.get('unprivileged')}`)." if prot_cfg else "."))
    add("- **Protected attribute is excluded from the model's features**, along with direct parent columns (e.g. `age` when auditing `age_group`).")
    add(f"- **Features after encoding:** {feature_count}.")
    if selected_eps is not None:
        add(f"- **Exponentiated Gradient tolerance:** ε = {selected_eps} (chosen on the validation split: max fairness gain with ≤ 5pp accuracy loss).")
    add("")

    add("## 2. Intended Use")
    add("- **Intended:** research, teaching and fairness auditing of tabular classifiers; comparing mitigation strategies with statistical uncertainty.")
    add(f"- **Out of scope:** making real decisions about any {labels['subject'].lower()}. These benchmark datasets are historical, contain known label bias, and the models were not validated for deployment.")
    add("")

    add("## 3. Datasheet — Training Data")
    add(f"- **Dataset:** {dataset_name}")
    add(f"- **Source:** {source}")
    add(f"- **Records after cleaning:** {kpis.get('total_records', 'n/a'):,}" if isinstance(kpis.get("total_records"), int) else f"- **Records after cleaning:** {kpis.get('total_records', 'n/a')}")
    if dedup_info:
        compas_note = " COMPAS rows are also filtered to `days_b_screening_arrest` within ±30 days, as in ProPublica's analysis." if dataset_key == "compas" else ""
        add(f"- **Raw rows:** {dedup_info.get('raw_rows', 'n/a'):,}; exact duplicates removed: {dedup_info.get('exact_duplicates_removed', 'n/a')}.{compas_note}")
    add(f"- **Splits (stratified on outcome × protected group):** train {split_sizes.get('train')}, validation {split_sizes.get('val')}, test {split_sizes.get('test')}.")
    add(f"- **Historical {labels['favorable_rate'].lower()}:** {_f(kpis.get('overall_positive_rate', 0) * 100, 1)}%; base-rate gap across `{protected_col}` groups: {_f(kpis.get('base_rate_disparity', 0) * 100, 1)} pp.")
    if kpis.get("group_rates"):
        add("- **Favorable rate by group:** " + ", ".join(f"{g}: {_f(r * 100, 1)}%" for g, r in kpis["group_rates"].items()))
    if dataset_key == "compas":
        add("- **Leakage control:** COMPAS score outputs (`decile_score`, `score_text`, …) and future-outcome fields are removed — the audited model never sees the instrument it is compared against.")
    add("- **Known data limitations:** see `docs/limitations.md` and `docs/dataset_documentation.md`.")
    add("")

    add("## 4. Predictive Performance (test split)")
    add("| Metric | Value |\n|---|---|")
    for k, name in [("accuracy", "Accuracy"), ("balanced_accuracy", "Balanced accuracy"), ("f1_score", "F1 (label 1)"), ("roc_auc", "ROC-AUC")]:
        add(f"| {name} | {_f(baseline_pred_metrics.get(k))} |")
    add("")

    add("## 5. Fairness Evaluation (baseline, test split)")
    add("Values are full-test-set point estimates; CIs are 95% bootstrap (500 resamples). Significance uses the CI of the **signed** gap between fixed reference groups (a CI of an absolute gap almost never contains 0).\n")
    add("| Metric | Value | 95% CI (absolute) | 95% CI (signed gap) | Significant |\n|---|---|---|---|---|")
    for key, name in [("demographic_parity_diff", "Demographic parity diff"), ("equalized_odds_diff", "Equalized odds diff"),
                      ("equal_opportunity_diff", "Equal opportunity diff"), ("predictive_parity_diff", "Predictive parity diff")]:
        if key in baseline_fairness:
            add(_metric_row(name, baseline_fairness[key]))
    add("")

    if intersectional:
        g = intersectional["gaps"]
        add("### Intersectional audit")
        add(f"- Attributes: {intersectional.get('label', '')}; subgroups with n < {intersectional['min_count']} excluded ({intersectional['n_excluded']} excluded, {intersectional['n_included']} included).")
        add(f"- Max–min selection-rate gap across intersections: **{_f(g['demographic_parity_diff'])}** "
            f"(highest: {intersectional.get('highest_selection_group')}, lowest: {intersectional.get('lowest_selection_group')}).")
        add("")

    if calibration and not calibration["summary"].empty:
        add("### Calibration by group (P(label = 1))")
        add("| Group | n | Brier | ECE |\n|---|---|---|---|")
        for _, r in calibration["summary"].iterrows():
            add(f"| {r['group']} | {r['count']} | {_f(r['brier_score'])} | {_f(r['ece'])} |")
        add("")

    if mitigations:
        add("## 6. Mitigations")
        add("Paired bootstrap of Δ = baseline DP − mitigated DP on identical resamples; significant iff the 95% CI of Δ is > 0.\n")
        add("| Technique | Accuracy | F1 | ROC-AUC | DP diff | Δ DP [95% CI] | Significant |\n|---|---|---|---|---|---|---|")
        for name, m in mitigations.items():
            pm, fm, sg = m.get("pred_metrics", {}), m.get("metrics", {}), m.get("significance", {})
            add(f"| {name} | {_f(pm.get('accuracy'))} | {_f(pm.get('f1_score'))} | {_f(pm.get('roc_auc'))} | "
                f"{_f(fm.get('demographic_parity_diff', {}).get('val'))} | {_f(sg.get('mean_delta'))} [{_f(sg.get('ci_low'))}, {_f(sg.get('ci_high'))}] | "
                f"{'**Yes**' if sg.get('is_significant') else 'No'} |")
        add("")

    add("## 7. Ethical Considerations & Caveats")
    add("- Group fairness metrics are mutually incompatible when base rates differ (calibration vs. equalized odds); choose the criterion that matches the harm in context.")
    add("- Mitigations that equalize selection rates can reduce accuracy and may worsen other metrics (check EO/PP columns).")
    add("- Small subgroups produce unstable estimates; intersectional and multi-group results exclude groups below the minimum size.")
    add("- Labels are historical decisions/outcomes and may themselves encode bias.")
    return "\n".join(L) + "\n"
